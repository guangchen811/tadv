from inspect import cleandoc

SYSTEM_TASK_DESCRIPTION = cleandoc("""Task-aware data validation aims to generate data validation constraints on the dataset where the downstream task is run. "Task" here refers to the downstream code. The system should generate effective and efficient constraints on the data.
*Effective*: The constraints should reflect whether the data is harmful to the downstream code. Constraints should fail if the data is harmful to the downstream code. Additionally, the constraints should be precise to reduce false positive alerts, meaning the constraints should not fail if the data is not harmful to the downstream task.
*Efficient*: The constraints should only be applied to columns accessed by the code. Constraints on unused columns would lead to redundant calculations and false positive alerts.

The task-aware data validation system consists of the following components:
1. *Column Access Detection*:
Input: 
    Statistics of the columns in the dataset.
    Downstream code snippet.
Output:
    Columns accessed by the downstream code snippet.
Given a dataset and the downstream code, this component finds the columns that are used in the code snippet. These columns are the accessed columns for the downstream task.
2. *Assumptions Extraction*:
Input:
    Statistics of the columns in the dataset.
    Columns accessed by the downstream code snippet.
    Downstream code snippet.
Output:
    User's assumptions about the accessed columns.
Given the accessed columns, the dataset statistics, and the downstream code, this component extracts the code's assumptions and requirements about the accessed columns. These assumptions are used to generate executable validation rules, ensuring the data meets the user's expectations.
3. *Rule Generation*:
Input:
    Statistics of the columns in the dataset.
    Columns accessed by the downstream code snippet.
    Code's assumptions about the accessed columns.
    Downstream code snippet.
Output:
    Validation rules in Great Expectations format.
Given a dataset described by name, columns with corresponding downstream code, the accessed columns and the user's assumptions. This component converts the code's assumptions and requirements into formal validation rules to ensure the data meets the code's expectations. The rules are generated in Great Expectations format.
""")

